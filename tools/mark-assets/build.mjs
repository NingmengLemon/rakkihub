// Builds the offline assets used by app/src/main/assets/html/mark.html.
//
// The page used to import every dependency from esm.sh and jsdelivr at runtime,
// which fails without network. This script bundles the same pinned versions into
// one local IIFE and copies KaTeX's CSS and fonts next to it. It also collects
// the licenses of every bundled package into a file that ships with the APK.
import { copyFile, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const outputDir = join(here, "..", "..", "app", "src", "main", "assets", "html");

await mkdir(join(outputDir, "fonts"), { recursive: true });

const entry = join(here, "entry.js");
await writeFile(
  entry,
  [
    'import MarkdownIt from "markdown-it";',
    'import markdownItKatexModule from "@vscode/markdown-it-katex";',
    'const markdownItKatex = markdownItKatexModule.default ?? markdownItKatexModule;',
    'import markdownItTaskLists from "markdown-it-task-lists";',
    'import katex from "katex";',
    'import "katex/dist/contrib/mhchem.mjs";',
    'import hljsModule from "highlight.js";',
    'const hljs = hljsModule.default ?? hljsModule;',
    'import { Base64 } from "js-base64";',
    'import DOMPurify from "dompurify";',
    "export { MarkdownIt, markdownItKatex, markdownItTaskLists, katex, hljs, Base64, DOMPurify };",
    "",
  ].join("\n"),
);

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  globalName: "MarkAssets",
  minify: true,
  target: ["chrome100"],
  outfile: join(outputDir, "mark.bundle.js"),
  legalComments: "eof",
  metafile: true,
});

await copyFile(
  join(here, "node_modules", "katex", "dist", "katex.min.css"),
  join(outputDir, "katex.min.css"),
);
await copyFile(
  join(here, "node_modules", "highlight.js", "styles", "atom-one-dark.min.css"),
  join(outputDir, "highlight.min.css"),
);

const fontDir = join(here, "node_modules", "katex", "dist", "fonts");
for (const font of await readdir(fontDir)) {
  await copyFile(join(fontDir, font), join(outputDir, "fonts", font));
}

function packageDirOf(input) {
  const marker = "node_modules/";
  const index = input.lastIndexOf(marker);
  if (index < 0) return null;
  const rest = input.slice(index + marker.length).split("/");
  const name = rest[0]?.startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
  return name ? join(input.slice(0, index + marker.length), name) : null;
}

async function collectLicenses(metafile) {
  const packages = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const dir = packageDirOf(input);
    if (!dir) continue;
    try {
      const pkg = JSON.parse(await readFile(join(dir, "package.json"), "utf8"));
      if (!pkg.name || !pkg.version || packages.has(`${pkg.name}@${pkg.version}`)) continue;
      const files = await readdir(dir);
      const licenseFile = files.find((file) => /^(licen[cs]e|copying)/i.test(file));
      const text = licenseFile ? await readFile(join(dir, licenseFile), "utf8") : "";
      packages.set(`${pkg.name}@${pkg.version}`, {
        name: pkg.name,
        version: pkg.version,
        license: pkg.license ?? "unknown",
        text: text.trim(),
      });
    } catch {
      // A generated or virtual module; not a distributable package.
    }
  }
  return [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
}

async function findMermaidLicense() {
  const root = join(here, "..", "..", "web-ui", "node_modules", ".pnpm");
  try {
    const dirs = await readdir(root);
    const preferred = dirs.find((dir) => dir.startsWith("mermaid@11.17.2")) ??
      dirs.find((dir) => dir.startsWith("mermaid@"));
    if (!preferred) return null;
    const packageDir = join(root, preferred, "node_modules", "mermaid");
    const license = await readFile(join(packageDir, "LICENSE"), "utf8");
    const pkg = JSON.parse(await readFile(join(packageDir, "package.json"), "utf8"));
    return { name: "mermaid", version: pkg.version, license: pkg.license ?? "MIT", text: license.trim() };
  } catch {
    // The web-ui dependencies are optional for regenerating this bundle.
  }
  return null;
}

const licenses = await collectLicenses(result.metafile);
const mermaid = await findMermaidLicense();
if (mermaid) licenses.push(mermaid);

const notices = [
  "# Third-party licenses for app/src/main/assets/html",
  "",
  "Generated by tools/mark-assets/build.mjs. Covers mark.bundle.js and, when",
  "present, the mermaid IIFE copied by the web build.",
  "",
  ...licenses.flatMap((pkg) => [
    `${"=".repeat(72)}`,
    `${pkg.name}@${pkg.version}`,
    `License: ${pkg.license}`,
    `${"=".repeat(72)}`,
    "",
    pkg.text || "The package did not ship a LICENSE file; see its package metadata.",
    "",
  ]),
];
await writeFile(join(outputDir, "THIRD_PARTY_LICENSES.txt"), notices.join("\n"), "utf8");

const size = (await readFile(join(outputDir, "mark.bundle.js"))).length;
console.log(
  `offline mark assets written to ${outputDir} (${size} bytes bundle, ${licenses.length} packages in notices)`,
);
